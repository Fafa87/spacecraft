// ---------------------------------------------------------------- tyranids
//
// v0.4 voice design (Space Marine 2 / Dawn of War): every Tyranid throat is a `creature`
// layer (glottal pulses + unison throats + open-phase breath + F4/F5 mandible resonances),
// over high-passed hisses with 2-6 kHz resonances, periodic mandible / stridulation clicks,
// bone-and-chitin crunches and convolution reverb. No AM'd brown noise, no wobbly lowpass
// tones (the v0.3 "farting" textures).

/** Stone hive vault / cavern IRs for the convolution reverb. */
const VAULT: ConvReverbOpts = { mix: 0.22, decay: 0.9, damp: 0.55, predelay: 0.012, seed: 11 };
const NAVE: ConvReverbOpts = { mix: 0.3, decay: 1.6, damp: 0.5, predelay: 0.02, seed: 23 };
const ABYSS: ConvReverbOpts = { mix: 0.34, decay: 2.6, damp: 0.45, predelay: 0.03, seed: 37 };
const NID_POST = {
  grit: 0.15,
  asym: 1.6,
  comp: { threshold: -18, ratio: 3.5, attack: 0.003, release: 0.1, makeup: 2 },
  conv: VAULT,
};

/** Gaunt / hormagaunt throat: small, pressed, rasping, high mandible resonances. */
const gaunt = (
  f0: Range,
  vowels: string[],
  d: number,
  gain = 1,
  at = 0,
  o: Partial<CreatureLayer> = {},
): Layer => ({
  kind: 'creature',
  f0,
  vowels,
  shift: 1.35,
  throat: [3400, 5300],
  voices: 3,
  detune: 28,
  jitter: 0.6,
  shimmer: 0.5,
  rasp: 0.3,
  breath: 0.5,
  oq: 0.42,
  drive: 2.6,
  env: { a: 0.006, h: d * 0.35, d },
  gain,
  at,
  ...o,
});
/** Big-beast throat: low, period-doubled, wide unison, chest + throat resonance. */
const beast = (
  f0: Range,
  vowels: string[],
  d: number,
  shift = 0.65,
  gain = 1,
  at = 0,
  hold = 0.2,
  o: Partial<CreatureLayer> = {},
): Layer => ({
  kind: 'creature',
  f0,
  vowels,
  shift,
  throat: [2500, 3800],
  voices: 4,
  detune: 34,
  jitter: 0.5,
  shimmer: 0.45,
  rasp: 0.65,
  breath: 0.35,
  oq: 0.6,
  drive: 3,
  q: 0.8,
  env: { a: 0.04, h: hold, d },
  gain,
  at,
  ...o,
});
/** Wet hiss: high-passed air with a 2-6 kHz resonance (`res`). */
const nhiss = (d: number, gain = 0.5, at = 0, res: Range = 3600, a = 0.02, hold = 0): Layer => ({
  kind: 'noise',
  color: 'pink',
  filter: { type: 'bp', freq: res, q: 0.8 },
  filter2: { type: 'peak', freq: res, q: 4, gain: 9 },
  env: { a, h: hold, d },
  gain,
  at,
});
/** Mandible clicks / stridulation: a periodic ratchet of tiny resonant clicks. */
const mandible = (
  d: number,
  rate: Range,
  gain = 0.4,
  at = 0,
  freq: [number, number] = [2600, 5600],
  hold = 0,
): Layer => ({
  kind: 'grains',
  src: 'click',
  regular: 0.18,
  rate,
  dur: [0.002, 0.005],
  freq,
  q: 7,
  env: { a: 0.004, h: hold, d },
  gain,
  at,
});
/** Bone / chitin crunch: dense cracking + an inharmonic carapace snap. */
const crunch = (d: number, gain = 0.6, at = 0, size = 1): Layer[] => [
  crack(0.004, 0.9 * gain, 2200 / size, at),
  crack(0.003, 0.6 * gain, 3000 / size, at + 0.018 * size),
  debris(d, [900, 60], [700 / size, 4200 / size], 0.6 * gain, at),
  {
    kind: 'metal',
    freq: 520 / size,
    partials: [1, 1.71, 2.93, 4.37, 6.9],
    decay: 0.06 * size,
    noise: 0.8,
    gain: 0.35 * gain,
    at,
  },
];
/** Wet tearing flesh (granular, low band). */
const wet = (d: number, gain = 0.4, at = 0, freq: [number, number] = [180, 950]): Layer => ({
  kind: 'grains',
  src: 'noise',
  rate: [300, 40],
  dur: [0.006, 0.028],
  freq,
  q: 3,
  env: e(d, 0.004),
  gain,
  at,
});

