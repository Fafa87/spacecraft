/**
 * Sound recipes: every SFX in the game as data. Each recipe is a stack of synthesis
 * layers rendered by synth.ts with the DSP toolkit in dsp.ts, then mastered (EQ,
 * saturation, compression, reverb) and rendered as several random variants.
 *
 * Design language (Warhammer 40k, "Space Marine 2 / Dawn of War"): every shot is
 *   transient crack + sub thump sweep (40-120 Hz) + filtered noise body
 *   + mechanical rattle + short corridor reverb, saturated and compressed.
 * Tyranids are formant-filtered throats, FM screeches and granular chitin.
 *
 * Add a sound: append a recipe (unique key), reference the key from content data or
 * the client, run `npm run assets`. A WAV in tools/assets-src/overrides/sfx/<key>.wav
 * replaces the procedural render (see docs/ART_PIPELINE.md).
 */
import type { Env } from './dsp.js';
import type { ReverbOpts as ReverbOptsLike } from './dsp.js';
import type { ConvReverbOpts } from './dsp.js';
import type { CreatureLayer, Layer, Range, Recipe } from './synth.js';

// ---------------------------------------------------------------- building blocks

const e = (d: number, a = 0.002, h = 0): Env => ({ a, h, d });
/** Envelope that holds for the whole loop. */
const HOLD: Env = { a: 0.001, h: 999, d: 1 };

const crack = (dur = 0.012, gain = 0.9, hp = 2800, at = 0, tone?: number): Layer => ({
  kind: 'click',
  dur,
  gain,
  hp,
  at,
  tone,
});
/** Sub thump: sine sweep, the chest-hit of every heavy weapon. */
const sub = (from: number, to: number, d: number, gain = 1, at = 0, curve = 0.5): Layer => ({
  kind: 'tone',
  wave: 'sine',
  freq: [from, to],
  env: e(d, 0.002),
  sweepTime: d * 0.6,
  curve,
  gain,
  at,
});
/** Filtered noise burst with a lowpass sweep (the "body" of a blast). */
const body = (
  lp: Range,
  d: number,
  gain = 0.8,
  at = 0,
  color: 'white' | 'pink' | 'brown' = 'pink',
  a = 0.002,
): Layer => ({
  kind: 'noise',
  color,
  filter: { type: 'lp', freq: lp, q: 0.8 },
  env: e(d, a),
  sweepTime: d * 0.7,
  curve: 0.6,
  gain,
  at,
});
const band = (
  freq: Range,
  q: number,
  d: number,
  gain = 0.5,
  at = 0,
  a = 0.002,
  color: 'white' | 'pink' | 'brown' = 'white',
): Layer => ({
  kind: 'noise',
  color,
  filter: { type: 'bp', freq, q },
  env: e(d, a),
  gain,
  at,
});
const hiss = (hp: number, d: number, gain = 0.4, at = 0, a = 0.01): Layer => ({
  kind: 'noise',
  color: 'white',
  filter: { type: 'hp', freq: hp, q: 0.7 },
  env: e(d, a),
  gain,
  at,
});
/** Mechanical clank / rattle. */
const clank = (
  freq: number,
  decay: number,
  gain = 0.3,
  at = 0,
  count = 1,
  spacing?: [number, number],
  noise = 0.45,
): Layer => ({
  kind: 'metal',
  freq,
  decay,
  gain,
  at,
  count,
  spacing,
  noise,
});
/** Granular debris / chitin crunch. */
const debris = (
  d: number,
  rate: Range,
  freq: [number, number],
  gain = 0.3,
  at = 0,
  a = 0.005,
): Layer => ({
  kind: 'grains',
  src: 'click',
  rate,
  dur: [0.002, 0.01],
  freq,
  q: 3,
  env: e(d, a),
  gain,
  at,
});
/** Wet organic squelch (granular band noise). */
const squelch = (d: number, gain = 0.5, at = 0, freq: [number, number] = [250, 1400]): Layer => ({
  kind: 'grains',
  src: 'noise',
  rate: [420, 60],
  dur: [0.004, 0.02],
  freq,
  q: 5,
  env: e(d, 0.003),
  gain,
  at,
});
const crackle = (d: number, density: Range, gain = 0.4, at = 0, hp = 1800, a = 0.002): Layer => ({
  kind: 'crackle',
  density,
  hp,
  env: e(d, a),
  gain,
  at,
});

